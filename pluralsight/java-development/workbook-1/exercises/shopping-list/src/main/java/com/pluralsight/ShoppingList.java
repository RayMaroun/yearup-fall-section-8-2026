// Exercise: Shopping List. Prints a list of at least ten items, one per line.
// No input, no math: the point is the routine (project, package, class, main, run, share).
public class ShoppingList {
    // main is where every Java program starts
    public static void main(String[] args) {
        // println prints the text and ends the line, so each call is one line of output
        System.out.println("My Shopping List:");
        System.out.println("- Apples");
        System.out.println("- Bananas");
        System.out.println("- Bread");
        System.out.println("- Milk");
        System.out.println("- Cheese");
        System.out.println("- Eggs");
        System.out.println("- Chicken");
        System.out.println("- Rice");
        System.out.println("- Potato");
        System.out.println("- Tomatoes");
    }
}
